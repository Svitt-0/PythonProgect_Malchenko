#Даны положительные числа A и B (A > Б). На отрезке длины A размещено максимально возможное количество отрезков длины B (без наложений). Не используя операции умножения и деления, найти количество отрезков Б, размещенных на отрезке A.
A = int(input("Введите длину A: "))
B = int(input("Введите длину B: "))
chetchic = 0
while A >= B:
    A = A - B
    chetchic += 1
print("Количество отрезков B:", chetchic)